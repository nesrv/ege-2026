'''
Алгоритм вычисления значения функции F(n), где n — целое число, задан следующими соотношениями:

F(n) = 1 при n < 10;

F(n) = (n + 3) * F(n - 3), если n >= 10.

Чему равно значение выражения F(247563)/519 - 477 * F(247560)/F(247557)?

---
Решение.

1) F(247563) = (247563 + 3) * F(247560) = 247566 * F(247560).

2) F(247560) = (247560 + 3) * F(247557) = 247563 * F(247557), значит F(247560) / F(247557) = 247563.

3) Подставляем:
   F(247563) / 519 - 477 * F(247560) / F(247557)
   = 247566 * F(247560) / 519 - 477 * 247563.

4) Заметим: 519 * 477 = 247563, т.е. 247563 = 519 * 477. Тогда
   247566 * F(247560) / 519 = 247566 * (247563 * F(247557)) / 519
   = 247566 * 477 * F(247557).

5) Итог (целое число):
   477 * 247566 * F(247557) - 477 * 247563
   = 477 * (247566 * F(247557) - 247563).

F(247557) — произведение множителей (n + 3) по цепочке n = 247557, 247554, ... до n < 10.
Численное значение ответа очень велико (~409257 десятичных знаков); ниже оно вычисляется программно.
'''

import sys

sys.set_int_max_str_digits(0)


def f247557():
    """F(247557) без полного кэша по всем n — только цепочка шаг −3."""
    acc = 1
    n = 247557
    while n >= 10:
        acc *= n + 3
        n -= 3
    return acc


c = f247557()
ans = 477 * (247566 * c - 247563)

# Эквивалентно исходной формуле с целочисленным делением:
# (247566 * 247563 * c) // 519 - 477 * (247563 * c // c)

print(ans)
