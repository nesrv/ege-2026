"""
Аналитическое решение задачи.

Анализ работы программы:
1. Начинаем справа от единиц в состоянии q₀
2. q₀ читает λ и идет влево в состояние q₁
3. q₁ читает единицы, идет влево в состояние q₂
4. q₂ и q₃ чередуются при движении влево через единицы
5. Когда достигаем λ слева, останавливаемся в q₂ или q₃

Заметим: программа не меняет символы на ленте! 
Она только читает и движется влево, меняя состояния.

В таблице переходов нет команд записи, значит символы остаются неизменными.
Изначально на ленте 57 единиц и 2 пустых символа (λ).
Нулей изначально нет, и они не появляются.

Но подождите... Давайте еще раз проверим таблицу.
В таблице указано: "0 → 0, L, q₃" - это означает что мы читаем 0, оставляем 0, идем влево в q₃.
Но если изначально нулей нет, откуда они возьмутся?

Проверим симуляцией.
"""

def quick_solve():
    """
    Быстрое решение без симуляции.
    
    Программа:
    - Начинает справа от единиц (на λ) в q₀
    - q₀: λ → λ, L, q₁  (идет влево на первую единицу, переходит в q₁)
    - Дальше движется влево через единицы, чередуя q₁, q₂, q₃
    - Останавливается когда встречает λ слева
    
    Важно: в таблице нет команд ЗАПИСИ! Все команды вида "X → X, ..."
    Это значит символы НЕ МЕНЯЮТСЯ на ленте.
    
    Начальное состояние: 57 единиц, 0 нулей
    Конечное состояние: 57 единиц, 0 нулей
    
    Ответ: 0
    """
    
    # Но проверим симуляцией на всякий случай
    tape = ['λ'] + ['1'] * 57 + ['λ']
    pos = len(tape) - 1
    state = 0
    steps = 0
    
    while steps < 100:
        steps += 1
        sym = tape[pos]
        
        if state == 0 and sym == 'λ':
            pos -= 1
            state = 1
        elif state == 1:
            if sym == '0':
                pos -= 1
                state = 3
            elif sym == '1':
                pos -= 1
                state = 2
            else:
                break
        elif state == 2:
            if sym == 'λ':
                break
            pos -= 1
            state = 3
        elif state == 3:
            if sym == 'λ':
                break
            pos -= 1
            state = 2
    
    zeros = tape.count('0')
    print(f"Анализ показал: нулей на ленте = {zeros}")
    print(f"Шагов выполнено: {steps}")
    return zeros


if __name__ == '__main__':
    zeros = quick_solve()
    print(f"\nОтвет: {zeros}")
