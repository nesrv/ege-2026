"""
Краткое решение задачи про машину Тьюринга.

Ключевое наблюдение: программа НЕ МЕНЯЕТ символы на ленте!
Все команды в таблице имеют вид "X → X, ...", то есть читают символ и оставляют его тем же.

Начальное состояние:
- Лента: λ 111...111 (57 единиц) λ
- Головка справа от единиц на пустой ячейке
- Состояние: q₀

Программа:
1. q₀ читает λ, идет влево → q₁
2. q₁ читает единицы, идет влево, переходит в q₂ или q₃
3. q₂ и q₃ чередуются при движении через единицы влево
4. Останавливается когда встречает λ слева

Результат: все 57 единиц остаются единицами, нулей не появляется.

Ответ: 0
"""

# Проверка через симуляцию
tape = [' '] + ['1'] * 57 + [' ']
pos = len(tape) - 1
state = 0

while True:
    if state == 0 and tape[pos] == ' ':
        pos -= 1
        state = 1
    elif state == 1:
        pos -= 1
        state = 3 if tape[pos] == '0' else 2
    elif state == 2:
        if tape[pos] == ' ':
            break
        pos -= 1
        state = 3
    elif state == 3:
        if tape[pos] == ' ':
            break
        pos -= 1
        state = 2

print(f"Количество нулей: {tape.count('0')}")
