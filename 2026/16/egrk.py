# Значение, которое нужно вычислить
n_target = 673

# Для G(n) нужны значения вплоть до 248045 + запас
# Так как G(n) для n < 248045 вызывает G(n+9), будем заполнять с конца
max_n_G = 248045 + 9  # небольшой запас

# Создаём массивы нужного размера
G = [0] * (max_n_G + 1)

# Заполняем G сверху вниз
for n in range(max_n_G, -1, -1):
    if n >= 248045:
        G[n] = n / 20 + 28
    else:
        G[n] = G[n + 9] - 4

# Теперь вычисляем F(n) для всех n от 0 до n_target
# Но F(n) для n >= 19 требует F(n-4), поэтому идём снизу вверх
F = [0] * (n_target + 1)

for n in range(0, n_target + 1):
    if n < 19:
        # Нужно убедиться, что n-7 не отрицательное
        if n - 7 >= 0:
            F[n] = 6 * (G[n - 7] - 36)
        else:
            # По условию для n < 7 формула не определена, но нам нужно только F(673), где всё ок
            F[n] = 0
    else:
        F[n] = F[n - 4] + 3580

# Вывод результата
print(F[n_target])