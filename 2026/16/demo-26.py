# Вычисление F(n) для больших n без рекурсии

n_target = 15548

# Так как в формулах используются n-3 и n-2, нужно обеспечить доступ к предыдущим значениям
# Создадим списки для G и F, индексированные от 0 до n_target
# Но чтобы не хранить миллионы лишних элементов, будем хранить только последние 3 значения G и F,
# однако из-за G(n) = G(n-2)+1 нам нужно чуть больше истории.

# На самом деле G(n) не зависит от F, её можно вычислить отдельно для всех n до n_target.
# Но из-за огромного n_target (15548) проще использовать итеративный подход с записью всех G,
# так как это всего 15 тысяч элементов — вполне допустимо для памяти.

# Сначала вычислим G(n) для всех n от 0 до n_target

G = [0] * (n_target + 1)  # создаём массив размером n_target+1

for n in range(0, n_target + 1):
    if n < 10:
        G[n] = 2 * n
    else:
        G[n] = G[n - 2] + 1

# Теперь вычислим F(n) для всех n от 0 до n_target
# Но F(n) использует G(n-3), поэтому нужно убедиться, что n-3 >=0
F = [0] * (n_target + 1)

for n in range(0, n_target + 1):
    if n - 3 >= 0:
        F[n] = 2 * (G[n - 3] + 8)
    else:
        # Для n < 3 формула не определена, но нам нужно только F(15548), где n>=3
        F[n] = 0  # или можно пропустить

# Вывод результата
print(F[n_target])