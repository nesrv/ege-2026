# Задача: количество n, для которых F(n) определено и F(n) ≤ 10^5

# Для маленьких n покажем вычисление
small_n = 30
F_small = [None] * (small_n + 1)

# База
for n in range(1, 4):
    F_small[n] = n + 1

# Заполняем для маленьких n
for n in range(4, small_n + 1):
    if n % 3 == 0:
        if F_small[n - 3] is not None:
            F_small[n] = F_small[n - 3] + n - 15
    # для не кратных 3 не заполняем (они не определены)

print("Значения для маленьких n (определены только n=1,2 и кратные 3):")
for n in range(1, small_n + 1):
    if F_small[n] is not None:
        print(f"F({n}) = {F_small[n]}")

print("\n" + "="*50 + "\n")

# Аналитическое решение
# Определены: n=1, n=2 и все n=3m, для которых F(3m) ≤ 10^5
# F(3m) = 16 + (3m(m+1))/2 - 15m ≤ 100000
# Решаем: m^2 - 9m - 66656 ≤ 0 → m ≤ 262
# Значит, m от 1 до 262 → 262 значения n=3m
# Плюс n=1 и n=2 → ещё 2
count = 262 + 2
print(f"Количество n: {count}")