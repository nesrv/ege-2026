'''
В файле 17_25356.txt содержится последовательность целых чисел. 
Её элементы могут принимать целые значения от -100 000 до 100 000 включительно. 

Определите количество троек элементов последовательности, в которых ни один из трёх элементов не является четырёхзначным числом, 
а сумма элементов тройки больше максимального элемента последовательности, оканчивающегося на 30.
В ответе запишите количество найденных троек чисел, затем максимальную из сумм элементов таких троек.

В данной задаче под тройкой подразумевается три идущих подряд элемента последовательности.

'''

def is_four_digit(n):
    return 1000 <= abs(n) <= 9999

def ends_with_30(n):
    return n % 100 == 30

with open('2026/17/17_25356.txt') as f:
    nums = [int(line) for line in f]

# Максимальный элемент, оканчивающийся на 30
max_30 = max(n for n in nums if ends_with_30(n))

count = 0
max_sum = 0

for i in range(len(nums) - 2):
    a, b, c = nums[i], nums[i + 1], nums[i + 2]
    
    # Ни один не четырёхзначный
    if is_four_digit(a) or is_four_digit(b) or is_four_digit(c):
        continue
    
    # Сумма > max_30
    s = a + b + c
    if s <= max_30:
        continue
    
    count += 1
    max_sum = max(max_sum, s)

print(count, max_sum)
