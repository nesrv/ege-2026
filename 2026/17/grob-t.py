'''
В файле 17_24677.txt содержится последовательность натуральных чисел. 
Её элементы могут принимать целые значения от 1 до 100 000 включительно. 
Определите количество пар последовательности, в которых только один из элементов является проклятым ведьмой. 
Проклятым считаются четырёхзначные числа кратные 666. 
В ответе запишите количество найденных пар, затем максимальную из сумм элементов таких пар. 
В данной задаче под парой подразумевается два идущих подряд элемента последовательности.
'''

def is_cursed(n):
    return 1000 <= n <= 9999 and n % 666 == 0

with open('2026/17/17_24677.txt') as f:
    nums = [int(line) for line in f]

count = 0
max_sum = 0

for i in range(len(nums) - 1):
    a, b = nums[i], nums[i + 1]
    # ровно один проклятый: XOR условий
    if is_cursed(a) != is_cursed(b):
        count += 1
        max_sum = max(max_sum, a + b)

print(count, max_sum)

