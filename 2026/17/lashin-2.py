'''
В файле 17_24372.txt содержится последовательность целых чисел. 
Её элементы могут принимать целые значения от -100 000 до 100 000 включительно.
Определите количество пар последовательности, в которых один положительный и один отрицательный элемент, 
а абсолютное значение их разности делится без остатка на количество отрицательных элементов последовательности, кратных 3. 
В ответе запишите количество найденных пар, затем максимальную из сумм элементов таких пар.
В данной задаче под парой подразумевается два идущих подряд элемента последовательности.
'''

with open('17_24372.txt') as f:
    nums = [int(line) for line in f]

# Количество отрицательных элементов, кратных 3
neg_div3_count = sum(1 for n in nums if n < 0 and n % 3 == 0)

count = 0
max_sum = None

for i in range(len(nums) - 1):
    a, b = nums[i], nums[i + 1]
    
    # Один положительный, один отрицательный
    if ((a > 0 and b < 0) or (a < 0 and b > 0)) and abs(a - b) % neg_div3_count == 0:
        count += 1
        s = a + b
        if max_sum is None or s > max_sum:
            max_sum = s

print(count, max_sum)

