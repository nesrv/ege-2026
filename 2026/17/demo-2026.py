'''
В файле 17_23757.txt содержится последовательность натуральных чисел.
Её элементы могут принимать целые значения от 1 до 100 000 включительно.
Определите количество пар последовательности, в которых только один из элементов является двузначным числом,
а сумма элементов пары кратна минимальному двузначному элементу последовательности. 
В ответе запишите количество найденных пар, затем максимальную из сумм элементов таких пар. 
В данной задаче под парой подразумевается два идущих подряд элемента последовательности.
'''

def is_two_digit(n):
    return 10 <= n <= 99

with open('2026/17/17_23757.txt') as f:
    nums = [int(line) for line in f]

# Находим минимальный двузначный элемент последовательности
min_two_digit = min(n for n in nums if is_two_digit(n))

count = 0
max_sum = 0

for i in range(len(nums) - 1):
    a, b = nums[i], nums[i + 1]
    
    # Ровно один двузначный
    if is_two_digit(a) == is_two_digit(b):
        continue
    
    # Сумма кратна минимальному двузначному
    s = a + b
    if s % min_two_digit != 0:
        continue
    
    count += 1
    max_sum = max(max_sum, s)

print(count, max_sum)

