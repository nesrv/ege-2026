'''
В файле 17_24539.txt содержится последовательность целых чисел. 
Её элементы могут принимать целые значения от -100 000 до 100 000 включительно.
Определите количество троек элементов последовательности, 
в которых ровно два из трёх элементов являются трёхзначными положительными числами, 
а произведение элементов тройки делится без остатка на максимальный трёхзначный элемент последовательности. 

В ответе запишите количество найденных троек чисел, затем максимальное абсолютное значение суммы элементов таких троек.

В данной задаче под тройкой подразумевается три идущих подряд элемента последовательности..
'''

def is_three_digit_positive(n):
    return 100 <= n <= 999

f = open ('17_24539.txt')
nums = [int(line) for line in f]

# Максимальный трёхзначный элемент (положительный)
max_three_digit = max(n for n in nums if 100 <= n <= 999)

count = 0
max_abs_sum = 0

for i in range(len(nums) - 2):
    a, b, c = nums[i], nums[i + 1], nums[i + 2]
    
    # Ровно два из трёх — трёхзначные положительные
    cnt = sum([is_three_digit_positive(a), is_three_digit_positive(b), is_three_digit_positive(c)])
    if cnt != 2:
        continue
    
    # Произведение делится на max_three_digit
    if (a * b * c) % max_three_digit != 0:
        continue
    
    count += 1
    max_abs_sum = max(max_abs_sum, abs(a + b + c))

print(count, max_abs_sum)

