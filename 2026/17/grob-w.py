'''
В файле 17.txt содержится последовательность натуральных чисел. 
Её элементы могут принимать целые значения от 1 до 100 000 включительно. 
Определите количество троек элементов последовательности, в которых 

есть хотя бы одно число, равное 2026,
ровно одно из чисел в тройке можно представить в виде произведения двух оставшихся чисел, 
а также сумма чисел является Новогодним числом. 

Новогоднее число - это такое число, которое не является шестизначным. 
В ответе запишите количество найденных троек, затем максимальную из сумм таких троек. 
В данной задаче под тройкой подразумевается три подряд идущих элемента..
'''

def is_new_year(n):
    # НЕ шестизначное: < 100000 или > 999999
    return n < 100000 or n > 999999

def count_products(a, b, c):
    # Сколько чисел равны произведению двух других
    cnt = 0
    if a == b * c: cnt += 1
    if b == a * c: cnt += 1
    if c == a * b: cnt += 1
    return cnt

with open('2026/17/17.txt') as f:
    nums = [int(line) for line in f]

count = 0
max_sum = 0

for i in range(len(nums) - 2):
    a, b, c = nums[i], nums[i + 1], nums[i + 2]
    
    # Условие 1: хотя бы одно = 2026
    if 2026 not in (a, b, c):
        continue
    
    # Условие 2: ровно одно число = произведение двух других
    if count_products(a, b, c) != 1:
        continue
    
    # Условие 3: сумма - новогоднее число
    s = a + b + c
    if not is_new_year(s):
        continue
    
    count += 1
    max_sum = max(max_sum, s)

print(count, max_sum)

