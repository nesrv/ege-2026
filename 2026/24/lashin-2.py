'''
(Иглин К.) Текстовый файл состоит из десятичных цифр и заглавных букв латинского алфавита. Определите в прилагаемом файле последовательность из максимального количества идущих подряд символов, удовлетворяющую условию: в ней ровно 80 отдельных слов (слова - это последовательности подряд идущих букв, отделенные друг от друга хотя бы одной цифрой).

В ответе запишите число - порядковый номер в файле первого символа найденной последовательности.

Для выполнения этого задания следует написать программу.

Примечание. В прилагаемом файле нумерация символов начинается с нуля.

--- На пальцах ---

Сканируем подстроку слева направо: новое «слово» начинается с буквы, если перед ней в подстроке нет буквы (начало или после цифры). Два указателя l, r и счётчик слов; расширяем r, при cnt > 80 двигаем l и поправляем cnt за O(1). При cnt == 80 обновляем максимум длины; при равной длине — меньший индекс l.
'''

from pathlib import Path

TARGET = 80

with open(Path(__file__).parent / '24_24374.txt') as f:
    s = f.read()

n = len(s)
l = 0
cnt = 0
best_len = -1
best_l = 0

for r in range(n):
    if s[r].isalpha() and (r == l or not s[r - 1].isalpha()):
        cnt += 1
    while cnt > TARGET:
        if s[l].isalpha():
            if not (l + 1 <= r and s[l + 1].isalpha()):
                cnt -= 1
        l += 1
    if cnt == TARGET:
        cur = r - l + 1
        if cur > best_len or (cur == best_len and l < best_l):
            best_len = cur
            best_l = l

print(best_l)
