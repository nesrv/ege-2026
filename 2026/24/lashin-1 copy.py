'''
(В. Лашин) Текстовый файл состоит из десятичных цифр и заглавных букв латинского алфавита. Определите в прилагаемом файле подстроку максимальной длины, у которой префикс будет совпадать с суффиксом. Префиксом и суффиксом подстроки не может являться сама подстрока.

В информатике принято называть префиксом и суффиксом следующие понятия:

Префикс — начало строки.

Суффикс — её конец.

Например, у строки "ЕГЭ", префиксы будут "Е", "ЕГ", а суффиксы "Э", "ГЭ"
В ответе запишите число — количество символов в найденной последовательности.

--- На пальцах ---


'''

from pathlib import Path




def solve():
    with open(Path(__file__).parent / '24_24196.txt') as f:
       s = f.read().strip()
    
    n = len(s)
    max_len = 0
    
    # Перебираем все возможные длины подстрок
    for length in range(n, 0, -1):
        for start in range(n - length + 1):
            substring = s[start:start + length]
            # Проверяем префиксы и суффиксы
            for l in range(1, length):
                if substring[:l] == substring[-l:]:
                    if length > max_len:
                        max_len = length
                    break
            if max_len > 0:
                break
        if max_len > 0:
            break
    
    return max_len

print(solve())