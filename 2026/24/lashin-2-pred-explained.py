# -*- coding: utf-8 -*-
'''
(Иглин К.) В файле — цифры и заглавные латинские буквы. Нужна самая длинная подстрока,
в которой ровно 80 «слов»: максимальные цепочки подряд идущих букв; между двумя словами
в подстроке есть хотя бы одна цифра.

Ответ: индекс с нуля первого символа такой подстроки (при равной максимальной длине —
меньший индекс).

Файл данных: 24_24374.txt рядом со скриптом.

================================================================================
Условие «новое слово» справа (переменная pred)
================================================================================

Идём слева направо по окну [L, R]. Новое слово начинается, когда видим букву, а слева
от неё в уже просмотренном хвосте «как будто после цифры» — т.е. либо это самый левый
символ окна в момент добавления R, либо предыдущий символ не буква.

Удобно хранить pred ∈ {'цифра', 'слово'}:
  • «цифра»  — последний обработанный символ на позиции < R не буква (или R=0 в начале
    цикла по всей строке: перед самым первым символом считаем разделитель).
  • «слово»  — мы внутри блока букв (продолжение того же слова).

При расширении R:
  если s[R] — буква и pred == 'цифра'  → началось новое слово, count += 1, pred = 'слово';
  если s[R] — буква и pred == 'слово'  → та же цепочка букв, count не меняем;
  если s[R] не буква                  → pred = 'цифра'.

В начале: pred = 'цифра', чтобы первая буква файла открыла первое слово.

================================================================================
Сдвиг левой границы L (исправление типичной ошибки)
================================================================================

При count > 80 сдвигаем L вправо. Если убираем букву в позиции L, число слов уменьшается
только если эта буква была «отдельным» началом слова без продолжения буквой внутри того
же окна.

НЕЛЬЗЯ смотреть на s[L+1] вне зависимости от R: символ справа от L может выходить за
правую границу окна. Пример: окно из одной буквы, L == R. Тогда внутри окна справа от L
нет буквы — убирая эту букву, мы теряем слово → count -= 1. Если бы смотрели на глобальный
s[L+1] и там была буква за пределами окна, можно ошибочно не уменьшить count.

Правило: для буквы s[L] уменьшать count, если НЕ (L + 1 <= R и s[L + 1] — буква).
Цифру при сдвиге L count не меняет.

================================================================================
Ответ
================================================================================

Ведём mxln и best_L. Обновляем, когда count == 80 и длина R - L + 1 больше mxln, либо
длина равна mxln, но L меньше best_L (первое вхождение при той же длине).

Печатаем best_L один раз в конце.
'''

from pathlib import Path

TARGET = 80

with open(Path(__file__).parent / '24_24374.txt') as f:
    s = f.read()

L = 0
pred = 'цифра'
count = 0
mxln = 0
best_L = 0

for R in range(len(s)):
    if s[R].isalpha() and pred == 'цифра':
        count += 1
        pred = 'слово'
    elif not s[R].isalpha():
        pred = 'цифра'
    # если буква и pred уже 'слово' — продолжение того же слова, pred не трогаем

    while count > TARGET:
        if s[L].isalpha() and not (L + 1 <= R and s[L + 1].isalpha()):
            count -= 1
        L += 1

    if count == TARGET:
        cur = R - L + 1
        if cur > mxln or (cur == mxln and L < best_L):
            mxln = cur
            best_L = L

print(best_L)
