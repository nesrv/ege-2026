'''
Текстовый файл состоит из десятичных цифр и заглавных букв латинского алфавита. Определите в прилагаемом файле максимальное количество идущих подряд символов, среди которых подстроки 2025 встречается не менее 90 раз и при этом содержится ровно 80 букв Y.

В ответе запишите число – количество символов в найденной последовательности.
Для выполнения этого задания следует написать программу.

--- Объяснение «на пальцах» ---

1) «Ровно 80 букв Y» в подряд идущем куске строки значит: между краями куска стоят ровно 80 букв Y.
   Если разрезать строку по каждой Y, то кусок «с ровно 80 Y» — это 81 кусок БЕЗ Y подряд,
   между ними как раз 80 букв Y (как палочки между кусками колбасы).

2) В каждом куске без Y мы заранее считаем, сколько раз там встречается «2025».
   Сумма по 81 такому куску подряд = сколько раз «2025» во всём выбранном отрезке
   (буквы Y в «2025» не входят, так что разрез по Y ничего не ломает).

3) Длина отрезка = сумма длин этих 81 куска + 80 (сами буквы Y между ними).

4) Перебираем все возможные «окна» из 81 куска подряд, проверяем сумму «2025» ≥ 90,
   из подходящих берём максимальную длину.
'''

from pathlib import Path

with open(Path(__file__).parent / '24_23762.txt') as f:
    s = f.read()

# Куски между соседними Y: ...Y кусок1 Y кусок2 Y ...
parts = s.split('Y')
lengths = [len(p) for p in parts]
counts = [p.count('2025') for p in parts]

maxi = 0
# Окно из 81 куска ↔ ровно 80 букв Y внутри соответствующего отрезка исходной строки
for i in range(len(parts) - 80):
    total_len = sum(lengths[i : i + 81]) + 80
    total_2025 = sum(counts[i : i + 81])
    if total_2025 >= 90:
        maxi = max(maxi, total_len)

print(maxi)