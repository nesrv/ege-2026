'''
Задание 24 (№27634).

Текстовый файл состоит из символов T, U, V, W, X, Y и Z.

Определите в прилагаемом файле минимальное количество идущих подряд символов (длину непрерывной подпоследовательности), среди которых символ Z встречается не менее 270 раз.

Для выполнения этого задания следует написать программу.

--- На пальцах ---

Нужен самый короткий подряд идущий отрезок, внутри которого ≥ 270 букв Z.
Берём позиции всех Z: z[0], z[1], … Если в отрезке ровно 270-й по счёту Z стоит в z[k+269],
а первый в этом окне — z[k], то длина отрезка z[k+269] − z[k] + 1.
Перебираем k и берём минимум.
'''

s = open(r'2026\24\24_27634.txt').read()


z = [i for i, c in enumerate(s) if c == 'Z']

min_len = 10**18

for k in range(len(z) - 269):
    pervaya = z[k]
    poslednyaya = z[k + 269]
    dlina = poslednyaya - pervaya + 1
    if dlina < min_len:
        min_len = dlina

# min_len = min(z[k + 269] - z[k] + 1 for k in range(len(z) - 269))

print(min_len)

