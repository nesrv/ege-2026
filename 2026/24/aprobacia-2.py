'''
Текстовый файл состоит из символов, обозначающих заглавные буквы латинского алфавита и цифры от 1 до 9 включительно.
Определите в прилагаемом файле максимальное количество идущих подряд символов, которые могут представлять запись числа в двенадцатеричной системе счисления.

Для выполнения этого задания следует написать программу.

Примечание. Цифры, числовое значение которых превышает 9, обозначены латинскими буквами начиная с буквы А.


--- На пальцах ---

В двенадцатеричной системе допустимы «цифры» с значениями 0…11: 0–9, затем A = 10, B = 11.
В файле есть только 1–9 и буквы, значит подходит любой подряд из символов из набора 1–9, A, B.
Буква C и дальше уже значение ≥ 12 — в двенадцатеричной записи не бывает. Идём по строке и считаем длину текущего «хорошего» отрезка.

'''

from pathlib import Path

with open(Path(__file__).parent / '24_27777.txt') as f:
    s = f.read()

ok = set('123456789AB')
maxi = 0
tek = 0
for c in s:
    if c in ok:
        tek += 1
        maxi = max(maxi, tek)
    else:
        tek = 0

print(maxi)

