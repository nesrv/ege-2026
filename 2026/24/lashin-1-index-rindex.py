'''
Задача: максимальная длина подряд идущего отрезка, у которого какой-то префикс совпадает с суффиксом
(не вся строка целиком).

--- Простое объяснение этого решения ---

1) Берём любой символ b, который встречается в строке. Самое левое вхождение — позиция l, самое правое — r.
   Отрезок от l до r включительно начинается и заканчивается одной и той же буквой b, значит у него уже есть
   «совпадение краёв» длины 1 (первый и последний символ одинаковые).

2) Дальше можно удлинить отрезок вправо: пока символ сразу после «левого хвоста» совпадает с символом
   на таком же расстоянии после «правого хвоста» (s[l+1+sd] и s[r+1+sd]), добавляем по одному символу —
   счётчик sd.

3) Длина такого отрезка: (r − l + 1) + sd. Перебираем все разные символы b из строки и берём максимум.

Ответ на файле 24_24196.txt: 1000002.
'''

from pathlib import Path

with open(Path(__file__).parent / '24_24196.txt') as f:
    s = f.read()

n = len(s)
best = 0
for b in s:
    l, r = s.index(b), s.rindex(b)
    sd = 0
    while r + sd + 1 < n and s[l + sd + 1] == s[r + sd + 1]:
        sd += 1
    best = max(best, r - l + 1 + sd)

print(best)
