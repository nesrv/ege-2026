'''
(В. Лашин) Текстовый файл 24196.txt состоит из десятичных цифр и заглавных букв латинского алфавита. Определите в прилагаемом файле подстроку максимальной длины, у которой префикс будет совпадать с суффиксом. Префиксом и суффиксом подстроки не может являться сама подстрока.

В информатике принято называть префиксом и суффиксом следующие понятия:

Префикс — начало строки.

Суффикс — её конец.

Например, у строки "ЕГЭ", префиксы будут "Е", "ЕГ", а суффиксы "Э", "ГЭ"
В ответе запишите число — количество символов в найденной последовательности.

--- На пальцах ---

1) Нужна подстрока T, у которой есть «граница»: первые k символов совпадают с последними k (1 ≤ k < |T|).
   Сама строка T целиком префиксом/суффиксом не считается — поэтому k строго меньше длины T.

2) Перебираем левый конец подстроки i и смотрим суффикс исходной строки t = s[i:]. Любая подстрока,
   начинающаяся в i, — это префикс t длины L.

3) Для строки t считают Z-функцию: Z[j] — сколько символов с позиции j совпадает с началом t.
   Граница длины k у префикса t длины L есть тогда и только тогда, когда для j = L − k выполняется
   Z[j] ≥ L − j, то есть Z[j] + j ≥ L.

4) При росте L от 2 до |t| множество допустимых j — это 1 … L−1; максимум выражения Z[j]+j на нём
   можно вести за O(1) на шаг: добавляем только j = L−1. Если maxvj ≥ L — для этого i подходит длина L.

5) Ответ — максимум таких L по всем i. В ответе — число символов (длина подстроки).

Сложность O(n²) по времени; при ~10⁶ символов в CPython прогон может занять много времени — удобнее PyPy,
проверка на префиксе строки при отладке или перенос на C++ на экзамене. Z считается по bytes и смещению,
чтобы не копировать s[i:] при каждом i.
'''

from pathlib import Path


def z_function_offset(b, off, m):
    """Z[j] для подстроки b[off : off+m] (без копирования среза)."""
    z = [0] * m
    if m == 0:
        return z
    z[0] = m
    l = r = 0
    for i in range(1, m):
        if i <= r:
            z[i] = min(r - i + 1, z[i - l])
        while i + z[i] < m and b[off + z[i]] == b[off + i + z[i]]:
            z[i] += 1
        if i + z[i] - 1 > r:
            l, r = i, i + z[i] - 1
    return z


with open(Path(__file__).parent / '24_24196.txt', 'rb') as f:
    b = f.read()

n = len(b)
best = 0

for i in range(n):
    m = n - i
    z = z_function_offset(b, i, m)
    maxvj = 0
    for L in range(2, m + 1):
        j = L - 1
        v = z[j] + j
        if v > maxvj:
            maxvj = v
        if maxvj >= L:
            best = max(best, L)

print(best)
