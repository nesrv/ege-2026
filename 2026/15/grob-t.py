ans = 10**9

# Заданные отрезки
B_start, B_end = 5, 13
O_start, O_end = 12, 105

# Перебираем возможные значения A (натуральные числа)
for A in range(1, 1000):
    # Перебираем все возможные x (натуральные числа)
    for x in range(1, 200):
        # Проверяем условие для текущего x
        # Выражение ложно, когда:
        # 1. x < 110 (первая часть ложна)
        # 2. x не в B и не в O (посылка импликации истинна)
        # 3. mod(x, A) = 0 (следствие импликации ложно)
        
        if (x < 110) and not (B_start <= x <= B_end) and not (O_start <= x <= O_end) and (x % A == 0):
            # Нашли контрпример - это A не подходит
            break
    else:
        # Цикл по x завершился без break
        # Значит для всех x нет контрпримера
        ans = min(ans, A)

print(ans)