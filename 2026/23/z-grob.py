'''
(Лысенков О.) На заводе по производству новогодних подарков один из конвейеров заканчивает свою работу в клетке с координатами (2,5), исполнитель "Снеговик-доставщик" должен доставлять подарки с этого конвейера на склад, то есть в точку с координатами (70,70), с этой точки их уже расфасовывает другой "Снеговик-фасовщик". Дед Морозу стало интересно, сколько вариантов есть у "Снеговик-доставщик", чтобы доставить подарок с данного конвейера до склада, если у него есть следующие возможные варианты действий:

Сдвинуться на 1 вправо. Например, из точки с координатами (2,5) в точку (3,5).

Сдвинуться на 1 вниз. Например, из точки с координатами (2,5) в точку (2,6).

Сдвинуться по диагонали на 1 ячейку вниз и вправо. Например, из точки с координатами (2,5) в точку (3,6).

И помимо этого "Снеговик-доставщик" должен посещать не более 5 магических точек (точка называется магической, если сумма её координат чётная), а также проходит через точку (30,33), так как именно в этой точке стоит пункт проверки подарка перед его отправкой фасовщику.

К сожалению, из-за новогодней суеты Дедушке Морозу стало не до этой задачи, поэтому он просит у вас помощи, помогите ему и дайте ответ, иначе эта задача так и будет его терзать и, возможно, он забудет доставить чей-то подарок.

В качестве ответа укажите число возможных вариантов. В ответе укажите только число.

'''

# Идея: считаем рекурсией «сколько путей из (x,y) до (70,70)».
# @lru_cache — чтобы одинаковые состояния не пересчитывать (как в разборе 23).

from functools import lru_cache

@lru_cache(maxsize=None)
def puti(x, y, ost_mag, proverka):

    if x > 70 or y > 70:
        return 0

    # Магическая клетка: сумма координат чётная
    if (x + y) % 2 == 0:
        if ost_mag == 0:
            return 0
        ost_mag -= 1

    if x == 70 and y == 70:
        return 1 if proverka else 0

    proverka = proverka or (x == 30 and y == 33)

    return (puti(x + 1, y, ost_mag, proverka) +
            puti(x, y + 1, ost_mag, proverka) +
            puti(x + 1, y + 1, ost_mag, proverka))

print(puti(2, 5, 5, False))

