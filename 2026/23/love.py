'''
Рыцарь отправляется в самое сложное испытание в своей жизни под название Вторая Часть, добраться до этого путешествия он может тремя способами:
A. Пешком – дешево и сердито (Прибавить 2)
B. На верном коне (Прибавить 8)
C. Оследить дракона – сомнительно, но окей (Умножить на 3)

Сколько существует возможных вариантов добраться из дома рыцаря числа 14 до границы Первой части числа 42, при условии, что Оследить дракона можно не более 1 раза за поход (потом он нас сожжет), а пешком нельзя идти более двух раз подряд (силы нужно беречь).

'''

# Как в z-grob.py: рекурсия + @lru_cache по состоянию.

from functools import lru_cache

@lru_cache(maxsize=None)
def puti(x, mozhno_x3, podryad_A):
    # x — текущее число
    # mozhno_x3 — 1, если команду «×3» ещё не применяли
    # podryad_A — сколько раз подряд уже шли пешком (не больше 2 подряд)

    if x > 42:
        return 0
    if x == 42:
        return 1

    s = 0
    s += puti(x + 8, mozhno_x3, 0)
    if mozhno_x3:
        s += puti(x * 3, 0, 0)
    if podryad_A < 2:
        s += puti(x + 2, mozhno_x3, podryad_A + 1)

    return s

print(puti(14, 1, 0))

# 12
