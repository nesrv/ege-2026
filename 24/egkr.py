'''
Задание 24 (№25361).

Текстовый файл состоит из десятичных цифр и заглавных букв латинского алфавита. Определите в прилагаемом файле максимальное количество идущих подряд символов, среди которых буква F встречается ровно 76 раз, чётная цифра встречается ровно один раз, искомая последовательность начинается с этой единственной чётной цифры.

В ответе запишите число – количество символов в найденной последовательности.
Для выполнения этого задания следует написать программу.

--- Объяснение «на пальцах» ---

1) Подстрока начинается с чётной цифры (0,2,4,6,8) и не содержит другой чётной цифры — значит она целиком лежит
   от этой цифры до следующей чётной справа (следующую чётную в отрезок не берём).

2) В таком «коридоре» нужно ровно 76 букв F. Чтобы отрезок был максимально длинным, берём самую правую
   возможную 76-ю F от выбранного старта — после неё остаётся больше места под хвост.

3) После 76-й F в хвост можно добавлять только символы, которые не F и не чётная цифра (иначе получится 77-я F
   или вторая чётная).

4) Для каждой чётной цифры как старта считаем длину подходящего отрезка и берём максимум (предпосчёт позиций F
   и «первой плохой» позиции справа ускоряет большой файл).

'''

from pathlib import Path

CH = set('02468')

with open(Path(__file__).parent / '24_25361.txt') as f:
    s = f.read()

n = len(s)

# Позиции всех F — чтобы взять 76-ю от текущего старта
f_pos = [i for i, c in enumerate(s) if c == 'F']

# stop[i] — первая позиция ≥ i, где F или чётная (конец «хорошего» хвоста после 76-й F)
stop = [n] * (n + 1)
for i in range(n - 1, -1, -1):
    stop[i] = i if (s[i] == 'F' or s[i] in CH) else stop[i + 1]

# sled_ch[i] — первая чётная на отрезке [i, n) — правая граница коридора после старта в предыдущей чётной
sled_ch = [n] * (n + 1)
for i in range(n - 1, -1, -1):
    sled_ch[i] = i if s[i] in CH else sled_ch[i + 1]

maxi = 0
j = 0  # индекс первой F с позицией ≥ i
for i in range(n):
    while j < len(f_pos) and f_pos[j] < i:
        j += 1
    if s[i] not in CH:
        continue
    R = sled_ch[i + 1]
    if j + 75 >= len(f_pos) or f_pos[j + 75] >= R:
        continue
    pos76 = f_pos[j + 75]
    p = pos76 + 1
    if p >= R:
        kon = pos76
    else:
        kon = min(R - 1, stop[p] - 1)
    maxi = max(maxi, kon - i + 1)

print(maxi)
